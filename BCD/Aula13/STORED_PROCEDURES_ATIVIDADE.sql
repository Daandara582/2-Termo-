-- 6. classificar estoque: 0 SEM ESTOQUE / <=5 BAIXO / >5 NORMAL
DELIMITER $$

CREATE PROCEDURE CLASSIFICAR_ESTOQUE(IN P_ID_PRODUTO INT)
BEGIN
    DECLARE V_QUANTIDADE INT;

    SELECT QUANTIDADE
    INTO V_QUANTIDADE
    FROM ESTOQUE
    WHERE ID_PRODUTO = P_ID_PRODUTO;

    IF V_QUANTIDADE = 0 THEN
        SELECT 'SEM ESTOQUE' AS SITUACAO;
    ELSEIF V_QUANTIDADE <= 5 THEN
        SELECT 'ESTOQUE BAIXO' AS SITUACAO;
    ELSE
        SELECT 'ESTOQUE NORMAL' AS SITUACAO;
    END IF;
END $$

DELIMITER ;
CALL CLASSIFICAR_ESTOQUE(1);

