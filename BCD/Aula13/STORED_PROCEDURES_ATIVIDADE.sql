-- 11. adicionar_item_pedido(...) buscando o preço atual
DELIMITER $$

CREATE PROCEDURE ADICIONAR_ITEM_PEDIDO (
    IN P_ID_PEDIDO INT,
    IN P_ID_PRODUTO INT,
    IN P_QUANTIDADE INT
)
BEGIN
    DECLARE V_PRECO DECIMAL(10,2);

    IF P_QUANTIDADE <= 0 THEN
        SELECT 'QUANTIDADE INVÁLIDA: DEVE SER MAIOR QUE ZERO' AS MENSAGEM;
    ELSE
    
        SELECT PRECO
        INTO V_PRECO
        FROM PRODUTO
        WHERE ID_PRODUTO = P_ID_PRODUTO
          AND ATIVO = TRUE;

        
        IF V_PRECO IS NULL THEN
            SELECT 'PRODUTO NÃO ENCONTRADO OU INATIVO' AS MENSAGEM;
        ELSE
            INSERT INTO ITEM_PEDIDO (
                ID_PEDIDO,
                ID_PRODUTO,
                QUANTIDADE,
                PRECO_UNITARIO
            )
            VALUES (
                P_ID_PEDIDO,
                P_ID_PRODUTO,
                P_QUANTIDADE,
                V_PRECO
            );

            SELECT 'ITEM ADICIONADO COM SUCESSO' AS MENSAGEM;
        END IF;
    END IF;
END $$

DELIMITER ;

CALL ADICIONAR_ITEM_PEDIDO(1, 1, 2);

