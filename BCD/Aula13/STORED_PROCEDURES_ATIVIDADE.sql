-- 8. alterar_preco(...) impedindo valor <= 0
DELIMITER $$

CREATE PROCEDURE ALTERAR_PRECO (
    IN P_ID_PRODUTO INT,
    IN P_NOVO_PRECO DECIMAL(10,2)
)
BEGIN
    IF P_NOVO_PRECO <= 0 THEN
        SELECT 'PREÇO INVÁLIDO: O VALOR DEVE SER MAIOR QUE ZERO' AS MENSAGEM;
    ELSE
        UPDATE PRODUTO
        SET PRECO = P_NOVO_PRECO
        WHERE ID_PRODUTO = P_ID_PRODUTO;

        SELECT 'PREÇO ATUALIZADO COM SUCESSO' AS MENSAGEM;
    END IF;
END $$
DELIMITER ;
CALL ALTERAR_PRECO(1, 12.50);
CALL ALTERAR_PRECO(1, -5.00);

-- 9. criar_pedido(IN p_id_cliente INT, OUT p_id_pedido INT)
DELIMITER $$

CREATE PROCEDURE CRIAR_PEDIDO (
    IN P_ID_CLIENTE INT,
    OUT P_ID_PEDIDO INT
)
BEGIN
    START TRANSACTION;

    INSERT INTO PEDIDO (
        ID_CLIENTE,
        DATA_PEDIDO,
        STATUS_PEDIDO
    )
    VALUES (
        P_ID_CLIENTE,
        NOW(),
        'ABERTO'
    );

    SET P_ID_PEDIDO = LAST_INSERT_ID();

    COMMIT;
END $$
DELIMITER ;
CALL CRIAR_PEDIDO(1, @NOVO_PEDIDO);
SELECT @NOVO_PEDIDO AS ID_PEDIDO_CRIADO;

