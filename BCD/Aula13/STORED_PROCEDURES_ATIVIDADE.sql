-- 2. buscar_produto_por_nome(IN p_busca VARCHAR(100))
DELIMITER $$

CREATE PROCEDURE BUSCAR_PRODUTO_POR_NOME(IN P_BUSCA VARCHAR(100))
BEGIN
    SELECT ID_PRODUTO AS CÓDIGO, NOME, PRECO
    FROM PRODUTO
    WHERE NOME LIKE CONCAT('%', P_BUSCA, '%')
      AND ATIVO = TRUE
    ORDER BY NOME;
END $$

